class DemoSource:
    """Offline literature source backed by ``DEMO_PAPERS`` (or a custom paper list)."""

    name: str = "arxiv"

    def __init__(self, papers: Sequence[Paper] = DEMO_PAPERS, *, name: str = "arxiv") -> None:
        self.name = name
        self._papers = list(papers)
        self._bm25 = BM25Index([tokenize(f"{p.title} {p.abstract}") for p in self._papers])

    async def search(self, query: str, *, limit: int) -> list[Paper]:
        scores = self._bm25.scores(tokenize(query))
        ranked = sorted(
            range(len(self._papers)), key=lambda i: (-float(scores[i]), self._papers[i].id)
        )
        matched = [self._papers[i] for i in ranked if scores[i] > 0][:limit]
        return matched or self._papers[: min(limit, len(self._papers))]


_EVIDENCE_BLOCK_RE = re.compile(
    r"\[(?P<alias>E\d+)\]\s*(?:\([^\n]*\))?\n(?P<text>.*?)(?=\n\n\[E\d+\]|\Z)",
    re.DOTALL,
)
_SENTENCE_LINE_RE = re.compile(r"^\[(?P<sid>s\d+)\]\s*(?P<text>.+)$", re.MULTILINE)
_CHALLENGED_LINE_RE = re.compile(
    r"^\[(?P<cid>c\d+)\]\s*\(verdict=(?P<verdict>[a-z_]+)", re.MULTILINE
)


def _parse_prompt_evidence(prompt: str) -> list[tuple[str, str]]:
    return [
        (m.group("alias"), m.group("text").strip()) for m in _EVIDENCE_BLOCK_RE.finditer(prompt)
    ]


def _extract_sentences(text: str) -> list[str]:
    spans = split_sentences(text)
    return [text[s:e].strip() for s, e in spans if text[s:e].strip()]


class DemoLLM:
    """Deterministic, context-sensitive LLM that reads the prompt's evidence blocks.

    On the first synthesis pass it includes one deliberately ungrounded overclaim so
    that the Verifier + Skeptic loop can be observed in action; on revision (when a
    ``Skeptic Audit`` block is present in the prompt) it drops the overclaim and emits
    only evidence-backed statements.
    """

    def __init__(self, *, inject_initial_overclaim: bool = True) -> None:
        self._inject_overclaim = inject_initial_overclaim
        self.calls: int = 0

    @property
    def model(self) -> str:
        return "aetheris-demo-1.0"

    async def generate_structured[T: BaseModel](
        self, *, system: str, prompt: str, schema: type[T]
    ) -> StructuredResult[T]:
        self.calls += 1
        produced: BaseModel
        if schema is ResearchPlan:
            produced = self._plan(prompt)
        elif schema is DraftOut:
            produced = self._synthesize(prompt)
        elif schema is ClaimsOut:
            produced = self._extract_claims(prompt)
        elif schema is VerificationOut:
            produced = self._verify(prompt)
        elif schema is SkepticOut:
            produced = self._skeptic(prompt)
        else:
            raise TypeError(f"DemoLLM does not support schema {schema.__name__}")

        validated = schema.model_validate_json(produced.model_dump_json())
        usage = TokenUsage(
            input_tokens=max(32, (len(system) + len(prompt)) // 4),
            output_tokens=max(24, len(produced.model_dump_json()) // 4),
        )
        return StructuredResult(value=validated, usage=usage, model=self.model, attempts=1)

    def _plan(self, prompt: str) -> ResearchPlan:
        q = prompt.split("Research question:", 1)[-1].strip()
        q_tokens = " ".join(tokenize(q)[:5]) or "retrieval augmented generation factuality"
        return ResearchPlan(
            objective=f"Systematically investigate and verify literature evidence on: {q}",
            sub_questions=[
                SubQuestion(
                    question=("What empirical gains do the core mechanisms achieve on benchmarks?"),
                    rationale=(
                        "Establishes primary quantitative baselines from peer-reviewed studies."
                    ),
                    search_queries=[
                        f"{q_tokens} benchmark evaluation",
                        "retrieval augmented generation open domain question answering",
                    ],
                ),
                SubQuestion(
                    question=(
                        "How do hybrid graph retrieval and atomic verification improve recall?"
                    ),
                    rationale=(
                        "Evaluates multi-hop GraphRAG, FActScore, and SciFact methodologies."
                    ),
                    search_queries=[
                        "GraphRAG reciprocal rank fusion multi hop recall",
                        "FActScore SciFact atomic claim verification",
                    ],
                ),
                SubQuestion(
                    question=(
                        "Under what failure modes or noisy contexts does performance degrade?"
                    ),
                    rationale=("Identifies counter-evidence, citation fabrication, and limits."),
                    search_queries=[
                        "noisy context hallucination amplification citation entailment",
                        "adversarial skeptic mechanical quote grounding",
                    ],
                ),
            ],
        )

    def _synthesize(self, prompt: str) -> DraftOut:
        evidence = _parse_prompt_evidence(prompt)
        is_revision = "Skeptic Audit" in prompt

        sub_qs = re.findall(r"^\d+\.\s+(.+)$", prompt, flags=re.MULTILINE)
        if not sub_qs:
            sub_qs = ["Empirical Findings", "Verification & Failure Modes"]

        sections: list[_SectionOut] = []
        ev_idx = 0
        for sec_i, heading in enumerate(sub_qs):
            sents: list[_SentenceOut] = []
            for _ in range(2):
                if ev_idx < len(evidence):
                    alias, chunk_text = evidence[ev_idx]
                    ev_idx += 1
                    chunk_sents = _extract_sentences(chunk_text)
                    chosen = chunk_sents[-1] if len(chunk_sents) > 1 else chunk_sents[0]
                    sents.append(_SentenceOut(text=chosen, citations=[alias]))
            # On the first pass only, append one overclaim in the final section so the
            # Verifier and Adversarial Skeptic loop demonstrably catch and fix it.
            if sec_i == len(sub_qs) - 1 and self._inject_overclaim and not is_revision and evidence:
                sents.append(
                    _SentenceOut(
                        text=(
                            "Standard RAG completely eliminates all citation errors and "
                            "achieves 100% entailment even under noisy distraction contexts."
                        ),
                        citations=[evidence[0][0]],
                    )
                )
            if sents:
                sections.append(_SectionOut(heading=heading, sentences=sents))

        title = (
            "Verified Synthesis Report (Revised after Skeptic Audit)"
            if is_revision
            else "Evidence-Grounded Scientific Synthesis Report"
        )
        return DraftOut(title=title, sections=sections)

    def _extract_claims(self, prompt: str) -> ClaimsOut:
        claims: list[_ClaimOut] = []
        for match in _SENTENCE_LINE_RE.finditer(prompt):
            sid = match.group("sid")
            text = match.group("text").strip()
            claims.append(_ClaimOut(sentence_id=sid, claim=text))
        return ClaimsOut(claims=claims)

    def _verify(self, prompt: str) -> VerificationOut:
        claim_part = prompt.split("Evidence excerpts:", 1)[0]
        claim_text = claim_part.replace("Claim:", "").strip()
        evidence = _parse_prompt_evidence(prompt)
        claim_lower = claim_text.lower()

        # Check for explicit contradiction (e.g. the injected overclaim about 100% entailment)
        if (
            "completely eliminates all citation errors" in claim_lower
            or "100% entailment" in claim_lower
        ):
            for alias, text in evidence:
                for sent in _extract_sentences(text):
                    if "31%" in sent or "27.4%" in sent or "fail strict entailment" in sent:
                        return VerificationOut(
                            verdict="refuted",
                            confidence=0.94,
                            rationale=(
                                "Directly contradicted by distraction experiments showing up to "
                                "31% of inline citations fail strict entailment and noisy "
                                "contexts raise unfaithful claims to 27.4%."
                            ),
                            quotes=[_QuoteOut(evidence=alias, quote=sent)],
                        )
            return VerificationOut(
                verdict="not_enough_info",
                confidence=0.61,
                rationale="No excerpt supports zero citation errors under noisy contexts.",
                quotes=[],
            )

        # Match the claim against sentences in the provided evidence blocks
        claim_tokens = set(tokenize(claim_text))
        best_alias = ""
        best_sent = ""
        best_overlap = 0.0
        for alias, text in evidence:
            for sent in _extract_sentences(text):
                sent_tokens = set(tokenize(sent))
                if not claim_tokens or not sent_tokens:
                    continue
                overlap = len(claim_tokens & sent_tokens) / max(1, len(claim_tokens))
                if overlap > best_overlap:
                    best_overlap = overlap
                    best_alias = alias
                    best_sent = sent

        if best_overlap >= 0.45 and best_sent:
            conf = min(0.97, round(0.76 + 0.22 * best_overlap, 2))
            return VerificationOut(
                verdict="supported",
                confidence=conf,
                rationale=f"Directly entailed by verbatim evidence in [{best_alias}].",
                quotes=[_QuoteOut(evidence=best_alias, quote=best_sent)],
            )

        return VerificationOut(
            verdict="not_enough_info",
            confidence=0.55,
            rationale="Retrieved excerpts do not contain sufficient direct evidence.",
            quotes=[],
        )

    def _skeptic(self, prompt: str) -> SkepticOut:
        issues: list[_IssueOut] = []
        for match in _CHALLENGED_LINE_RE.finditer(prompt):
            cid = match.group("cid")
            verdict = match.group("verdict")
            issues.append(
                _IssueOut(
                    claim_id=cid,
                    issue=(
                        f"Claim {cid} was marked '{verdict}': overgeneralises RAG reliability "
                        "and ignores distraction/noisy-context failure modes."
                    ),
                    counter_query=("adversarial skeptic mechanical quote grounding noisy context"),
                )
            )
        return SkepticOut(
            summary=(
                f"Identified {len(issues)} unsubstantiated or refuted claim(s); requesting "
                "targeted counter-evidence retrieval and draft revision."
            ),
            issues=issues,
        )
